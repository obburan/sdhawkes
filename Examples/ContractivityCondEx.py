    with open(param_file, 'w') as f:
        f.write("=" * 70 + "\n")
        f.write("CONTRACTIVITY CONDITION EXPERIMENT PARAMETERS\n")
        f.write("=" * 70 + "\n\n")
        
        f.write("EXPERIMENT METADATA\n")
        f.write("-" * 70 + "\n")
        f.write(f"Timestamp: {timestamp}\n")
        f.write(f"Subfolder: {os.path.basename(subfolder_path)}\n\n")
        
        f.write("CONTRACTIVITY SEARCH PARAMETERS\n")
        f.write("-" * 70 + "\n")
        f.write(f"Initial rho (rho_0): {rho_0}\n")
        f.write(f"Rho step size: {rho_step}\n")
        f.write(f"Minimum rho (rho_min): {rho_min}\n")
        f.write(f"Final rho achieved: {rho_final}\n")
        f.write(f"Number of feasible (rho, w) pairs found: {num_pairs}\n\n")
        
        f.write("LP SOLVER PARAMETERS\n")
        f.write("-" * 70 + "\n")
        f.write(f"Solver: {solver_name}\n")
        f.write(f"Constraint: w >= 1 elementwise (no normalization)\n\n")
        
        f.write("HAWKES PROCESS PARAMETERS\n")
        f.write("-" * 70 + "\n")
        f.write(f"Dimension: {dim}\n\n")
        
        f.write(f"Alpha (excitation matrix):\n")
        for row in alpha:
            f.write(f"  {row}\n")
        f.write("\n")
        
        f.write(f"Beta (decay matrix):\n")
