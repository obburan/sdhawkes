## LP Solver Parameter Constructors

def scipy_LP_params_constructor(H_matrices_list: List[np.ndarray], rho: float) -> Dict:
    """
    Construct LP problem parameters for scipy.optimize.linprog.
    
    Formulates the contractivity condition as a linear program:
        find w such that w·H(y) ≤ ρ·w (elementwise) for all y with constraint: w ≥ 1 elementwise
    
    Parameters:
    -----------
    H_matrices_list : list of np.ndarray
        List of H(y) matrices for each feasible state y
    rho : float
        Contractivity parameter ∈ (0,1)
        
    Returns:
    --------
    dict
        Dictionary with keys compatible with scipy.optimize.linprog:
        - 'c': objective function coefficients
        - 'A_ub': inequality constraint matrix
        - 'b_ub': inequality constraint bounds
        - 'A_eq': equality constraint matrix (or None)
        - 'b_eq': equality constraint bounds (or None)
        - 'bounds': variable bounds
        - 'method': solver method
        - 'options': solver options
    """
    # Enforce nonempty state space
    if len(H_matrices_list) == 0:
        raise ValueError("H_matrices_list cannot be empty")
    
    dim = H_matrices_list[0].shape[0]
    
    # Objective: we only care about feasibility, so use zero objective
    c = np.zeros(dim)
    
    # Inequality constraints: w @ (H(y)[:, i] - rho * e_i) <= 0 for all y, all i
    A_ub_list = []
    for H_y in H_matrices_list:
        for i in range(dim):
            # (w @ H(y))[i] <= rho * w[i]
            # sum_j w[j] * H(y)[j, i] <= rho * w[i]
            # sum_j w[j] * H(y)[j, i] - rho * w[i] <= 0
            # w @ (H(y)[:, i] - rho * e_i) <= 0
            e_i = np.zeros(dim)
            e_i[i] = 1
            row = H_y[:, i] - rho * e_i
            A_ub_list.append(row)
    
    A_ub = np.array(A_ub_list)
    b_ub = np.zeros(len(A_ub_list))
    
    # Constraint: w ≥ 1 elementwise (no normalization)
    A_eq = None
    b_eq = None
    bounds = [(1.0, None) for _ in range(dim)]
    
    return {
        'c': c,
        'A_ub': A_ub,
        'b_ub': b_ub,
        'A_eq': A_eq,
        'b_eq': b_eq,
        'bounds': bounds,
        'method': 'highs',
        'options': {'disp': False}
    }


def scipy_LP_solver(lp_params: Dict) -> Dict:
    """
    Solve LP using scipy.optimize.linprog.
    
    Parameters:
    -----------
    lp_params : dict
        Dictionary containing LP problem parameters from scipy_LP_params_constructor
        
    Returns:
    --------
    dict with keys:
        'feasible': bool
        'w': np.ndarray or None (optimal w if feasible)
        'status': str (solver status)
        'solve_time': float (seconds)
    """
    start_time = time.time()
    result = opt.linprog(
        lp_params['c'],
        A_ub=lp_params['A_ub'],
        b_ub=lp_params['b_ub'],
        A_eq=lp_params['A_eq'],
        b_eq=lp_params['b_eq'],
        bounds=lp_params['bounds'],
        method=lp_params['method'],
        options=lp_params['options']
    )
    solve_time = time.time() - start_time
    
    # Package results
    if result.success:
        return {
            'feasible': True,
            'w': result.x,
            'status': result.message,
            'solve_time': solve_time
        }
    else:
        return {
            'feasible': False,
            'w': None,
            'status': result.message,
            'solve_time': solve_time
        }


def solve_LP_given_rho(H_matrices_list: List[np.ndarray], rho: float, lp_solver: Callable, lp_params_constructor: Callable) -> Dict:
    """
    Solve LP feasibility problem for contractivity condition using provided solver and parameter constructor.
    
    Finds weight vector w such that w·H(y) ≤ ρ·w (elementwise) for all feasible states y. Uses the constraint: w ≥ 1 elementwise.
    
    Parameters:
    -----------
    H_matrices_list : list of np.ndarray
        List of H(y) matrices (L¹ norms of excitation kernels) for each feasible state y
    rho : float
        Contractivity parameter ∈ (0,1). Larger rho = easier to satisfy (looser condition)
    lp_solver : callable
        LP solver function that takes lp_params dict and returns result dict
    lp_params_constructor : callable
        Function that constructs LP parameters from (H_matrices_list, rho)
            
    Returns:
    --------
    dict
        Result dictionary from the solver with keys:
        - 'feasible': bool indicating if LP is feasible
        - 'w': np.ndarray or None (optimal w if feasible)
        - 'status': str (solver status message)
        - 'solve_time': float (seconds)
    """
    # Handle empty state space
    if len(H_matrices_list) == 0:
        return {'feasible': False, 'w': None, 'status': 'empty_state_space', 'solve_time': 0.0}
    
    # Construct LP parameters
    lp_params = lp_params_constructor(H_matrices_list, rho)
    
    # Solve LP
    return lp_solver(lp_params)

