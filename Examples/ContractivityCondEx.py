def plot_evolution_static(rho_list: List[float], w_list: List[np.ndarray], output_path: str, title: str = "Contractivity Vector Evolution") -> None:
    """
    Create static plot showing evolution of weight vectors w as rho changes.
    
    Visualizes w vectors as arrows from origin, colored by their corresponding rho value.
    Color gradient: blue (large ρ, easier condition) → red (small ρ, harder condition).
    
    This function is designed to be general and work for any dimension d, though it's
    most interpretable for d=2 (2D arrows).
    
    Parameters:
    -----------
    rho_list : list of float
        List of rho values (contractivity parameters)
    w_list : list of np.ndarray
        List of corresponding weight vectors w
    output_path : str
        Path to save the plot (e.g., 'w_evolution.png')
    title : str, optional
        Plot title (default: "Contractivity Weight Vector Evolution")
        
    Returns:
    --------
    None
        Saves plot to output_path
        
    Notes:
    ------
    - For d=2: Creates 2D arrow plot
    - For d>2: Creates parallel coordinates plot or component-wise visualization
    - Requires matplotlib
    """
    import datetime
    
    if len(rho_list) == 0:
        print("Warning: No data to plot (empty rho_list)")
        return
    
    rho_array = np.array(rho_list)
    w_array = np.array(w_list)  # Shape: (num_points, dim)
    dim = w_array.shape[1]
    
    # Create figure
    fig, ax = plt.subplots(figsize=(10, 8))
    
    if dim == 2:
        # 2D case: arrow plot
        # Normalize rho values to [0, 1] for colormap
        rho_normalized = (rho_array - rho_array.min()) / (rho_array.max() - rho_array.min() + 1e-10)
        
        # Use colormap: blue (high rho) to red (low rho)
        cmap = plt.cm.coolwarm_r  # reversed coolwarm: blue=high, red=low
        colors = cmap(rho_normalized)
        
        # Determine axis limits to make plot square
        # Find the maximum value across both w_1 and w_2 components
        w_max = max(np.max(w_array[:, 0]), np.max(w_array[:, 1]))
        axis_limit = w_max * 1.1  # Add 10% padding
        
        # Plot arrows
        for i, (w, color) in enumerate(zip(w_array, colors)):
            ax.arrow(0, 0, w[0], w[1], 
                    head_width=0.02, head_length=0.02, 
                    fc=color, ec=color, alpha=0.7, 
                    length_includes_head=True, linewidth=1.5)
        
        # Add colorbar (ensure vmax < 1 since rho must be strictly less than 1)
        # Set vmax to the smaller of: actual max or 0.99 (to ensure colorbar never shows >= 1)
        rho_max_display = min(rho_array.max(), 0.99)
        # Ensure vmin is also reasonable and less than vmax
        rho_min_display = min(rho_array.min(), rho_max_display - 0.01)
        sm = plt.cm.ScalarMappable(cmap=cmap, 
                                   norm=plt.Normalize(vmin=rho_min_display, vmax=rho_max_display))
        sm.set_array([])
        cbar = plt.colorbar(sm, ax=ax)
        cbar.set_label('ρ (contractivity parameter)', fontsize=12)
        # Format colorbar ticks to show they're all < 1
        cbar.ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, p: f'{x:.3f}'))
        
        # Labels and formatting
        ax.set_xlabel('$w_1$', fontsize=14)
        ax.set_ylabel('$w_2$', fontsize=14)
        ax.set_title(title, fontsize=16)
        ax.grid(True, alpha=0.3)
        ax.axhline(y=0, color='k', linewidth=0.5)
        ax.axvline(x=0, color='k', linewidth=0.5)
        
        # Set equal axis limits to make plot square
        ax.set_xlim(-0.05 * axis_limit, axis_limit)
        ax.set_ylim(-0.05 * axis_limit, axis_limit)
        ax.set_aspect('equal', adjustable='box')
        
        # Add text annotations for first and last (rho, w) pairs at top of plot
        first_rho, first_w = rho_array[0], w_array[0]
        last_rho, last_w = rho_array[-1], w_array[-1]
        text_y_pos = axis_limit * 0.95  # Position near top of plot
        ax.text(0.02, text_y_pos, 
                f'First: ρ={first_rho:.6f}, w=[{first_w[0]:.3f}, {first_w[1]:.3f}]',
                fontsize=10, verticalalignment='top', 
                bbox=dict(boxstyle='round', facecolor='wheat', alpha=0.5))
        ax.text(0.02, text_y_pos - axis_limit * 0.08,
                f'Last: ρ={last_rho:.6f}, w=[{last_w[0]:.3f}, {last_w[1]:.3f}]',
                fontsize=10, verticalalignment='top',
                bbox=dict(boxstyle='round', facecolor='lightblue', alpha=0.5))
        
    else:
        # Higher dimensional case: parallel coordinates plot
        for i, (rho, w) in enumerate(zip(rho_array, w_array)):
            # Normalize rho for color
            rho_norm = (rho - rho_array.min()) / (rho_array.max() - rho_array.min() + 1e-10)
            color = plt.cm.coolwarm_r(rho_norm)
            
            # Plot line connecting w components
            ax.plot(range(dim), w, '-o', color=color, alpha=0.6, linewidth=1.5)
        
        # Add colorbar (ensure vmax < 1 since rho must be strictly less than 1)
        # Set vmax to the smaller of: actual max or 0.99 (to ensure colorbar never shows >= 1)
        rho_max_display = min(rho_array.max(), 0.99)
        # Ensure vmin is also reasonable and less than vmax
        rho_min_display = min(rho_array.min(), rho_max_display - 0.01)
        sm = plt.cm.ScalarMappable(cmap=plt.cm.coolwarm_r, 
                                   norm=plt.Normalize(vmin=rho_min_display, vmax=rho_max_display))
        sm.set_array([])
        cbar = plt.colorbar(sm, ax=ax)
        cbar.set_label('ρ (contractivity parameter)', fontsize=12)
        # Format colorbar ticks to show they're all < 1
        cbar.ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, p: f'{x:.3f}'))
        
        # Labels
        ax.set_xlabel('Component index', fontsize=14)
        ax.set_ylabel('$w_i$', fontsize=14)
        ax.set_title(title, fontsize=16)
        ax.set_xticks(range(dim))
        ax.set_xticklabels([f'$w_{i+1}$' for i in range(dim)])
        ax.grid(True, alpha=0.3)
    
    plt.tight_layout()
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Static plot saved to: {output_path}")
    plt.close()


def plot_evolution_animated(rho_list: List[float], w_list: List[np.ndarray], output_path: str, title: str = "Contractivity Vector Evolution", 
                           interval: int = 200) -> None:
    """
    Create animated GIF showing how weight vector w evolves as rho decreases.
    
    Shows a "movie" of w changing over time (parameterized by rho) without an explicit
    rho axis. For d=2, animates an arrow; for d>2, animates a bar chart.
    
    Parameters:
    -----------
    rho_list : list of float
        List of rho values (contractivity parameters), should be in decreasing order
    w_list : list of np.ndarray
        List of corresponding weight vectors w
    output_path : str
        Path to save animation (must end in .gif)
    title : str, optional
        Base title for animation (default: "Contractivity Weight Vector Evolution")
    interval : int, optional
        Delay between frames in milliseconds (default: 200)
        
    Returns:
    --------
    None
        Saves animation to output_path
        
    Notes:
    ------
    - Uses pillow writer for GIF output
    - Animation shows rho value in title for each frame
    """
    if len(rho_list) == 0:
        print("Warning: No data to animate (empty rho_list)")
        return
    
    rho_array = np.array(rho_list)
    w_array = np.array(w_list)
    dim = w_array.shape[1]
    
    # Ensure output path ends with .gif
    if not output_path.endswith('.gif'):
        output_path += '.gif'
    
    writer = 'pillow'
    
    # Create figure
    fig, ax = plt.subplots(figsize=(10, 8))
    
    if dim == 2:
        # 2D case: animate arrow
        # Set axis limits based on data range
        w_max = np.max(np.abs(w_array)) * 1.2
        ax.set_xlim(-0.1, w_max)
        ax.set_ylim(-0.1, w_max)
        ax.set_xlabel('$w_1$', fontsize=14)
        ax.set_ylabel('$w_2$', fontsize=14)
        ax.grid(True, alpha=0.3)
        ax.set_aspect('equal', adjustable='box')
        
        # Initialize arrow
        arrow = ax.arrow(0, 0, w_array[0, 0], w_array[0, 1],
                        head_width=0.05*w_max, head_length=0.05*w_max,
                        fc='blue', ec='blue', linewidth=2,
                        length_includes_head=True)
        title_text = ax.set_title(f"{title}\nρ = {rho_array[0]:.6f}", fontsize=16)
        
        def update_arrow(frame):
            """Update function for animation"""
            ax.clear()
            ax.set_xlim(-0.1, w_max)
            ax.set_ylim(-0.1, w_max)
            ax.set_xlabel('$w_1$', fontsize=14)
            ax.set_ylabel('$w_2$', fontsize=14)
            ax.grid(True, alpha=0.3)
            ax.set_aspect('equal', adjustable='box')
            
            w = w_array[frame]
            ax.arrow(0, 0, w[0], w[1],
                    head_width=0.05*w_max, head_length=0.05*w_max,
                    fc='blue', ec='blue', linewidth=2,
                    length_includes_head=True)
            ax.set_title(f"{title}\nρ = {rho_array[frame]:.6f}", fontsize=16)
            return ax,
        
        anim = animation.FuncAnimation(fig, update_arrow, frames=len(rho_list),
                                      interval=interval, blit=False, repeat=True)
    
    else:
        # Higher dimensional case: animate bar chart
        # Set axis limits
        w_max = np.max(w_array) * 1.1
        w_min = min(0, np.min(w_array) * 1.1)
        
        ax.set_ylim(w_min, w_max)
        ax.set_xlabel('Component index', fontsize=14)
        ax.set_ylabel('$w_i$', fontsize=14)
        ax.set_xticks(range(dim))
        ax.set_xticklabels([f'$w_{i+1}$' for i in range(dim)])
        ax.grid(True, alpha=0.3, axis='y')
        
        # Initialize bars
        bars = ax.bar(range(dim), w_array[0], color='blue', alpha=0.7)
        title_text = ax.set_title(f"{title}\nρ = {rho_array[0]:.6f}", fontsize=16)
        
        def update_bars(frame):
            """Update function for animation"""
            w = w_array[frame]
            for bar, height in zip(bars, w):
                bar.set_height(height)
            title_text.set_text(f"{title}\nρ = {rho_array[frame]:.6f}")
            return bars + [title_text]
        
        anim = animation.FuncAnimation(fig, update_bars, frames=len(rho_list),
                                      interval=interval, blit=True, repeat=True)
    
    # Save animation
    print(f"Saving animation to: {output_path}")
    anim.save(output_path, writer=writer)
    print(f"Animation saved successfully")
    plt.close()


