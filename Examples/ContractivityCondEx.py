## Iterative Algorithms

def Rho_W_BisectionSearch(H_matrices_list: List[np.ndarray], rho_min: float = RHO_MIN, rho_max: float = RHO_MAX, tol: float = RHO_TOL, lp_solver: Callable = scipy_LP_solver, 
                                lp_params_constructor: Callable = scipy_LP_params_constructor, verbose: bool = True) -> Optional[Tuple[float, np.ndarray, int]]:
    """
    Find the minimum ρ satisfying contractivity condition using bisection search.
    
    Uses binary search to efficiently find the smallest rho value for which the LP is feasible. This is more efficient than line search when you only need the minimum rho, but doesn't provide the full trajectory of (rho, w) pairs needed for visualization.
    
    Since larger rho makes the LP easier to satisfy, we expect:
    - LP is feasible for rho close to 1
    - LP is infeasible for rho close to 0
    - There exists a critical rho* where the transition occurs
    
    Uses the constraint: w ≥ 1 elementwise (no normalization).
    
    Parameters:
    -----------
    H_matrices_list : list of np.ndarray
        List of H(y) matrices for each feasible state y
    rho_min : float, optional
        Lower bound for bisection search (default: RHO_MIN)
    rho_max : float, optional
        Upper bound for bisection search (default: RHO_MAX)
    tol : float, optional
        Tolerance for bisection convergence (default: RHO_TOL)
    lp_solver : callable, optional
        LP solver function (default: scipy_LP_solver)
    lp_params_constructor : callable, optional
        LP parameter constructor function (default: scipy_LP_params_constructor)
    verbose : bool, optional
        If True, print progress information (default: True)
        
    Returns:
    --------
    tuple of (rho_critical, w_critical, num_iterations) or None
        - rho_critical : float
            Minimum rho value for which LP is feasible (within tolerance)
        - w_critical : np.ndarray
            Weight vector w corresponding to rho_critical
        - num_iterations : int
            Number of bisection iterations performed
        Returns None if LP is infeasible even at rho_max
    """
    rho_plus = rho_max
    rho_minus = rho_min
    num_iterations = 0
    
    if verbose:
        print(f"Starting bisection search for minimum rho")
        print(f"Search interval: [{rho_min:.10f}, {rho_max:.10f}]")
        print(f"Tolerance: {tol}")
        print(f"Using solver: {lp_solver.__name__}")
        print("-" * 60)

    # Check upper bound
    U = solve_LP_given_rho(H_matrices_list, rho_plus, lp_solver, lp_params_constructor)
    num_iterations += 1
    if not U['feasible']:
        if verbose:
            print(f"LP infeasible even at rho_max = {rho_max:.10f}")
            print("No contractivity condition can be satisfied.")
        return None
    
    # Check lower bound
    L = solve_LP_given_rho(H_matrices_list, rho_minus, lp_solver, lp_params_constructor)
    num_iterations += 1
    if L['feasible']:
        if verbose:
            print(f"LP feasible at rho_min = {rho_minus:.10f}")
            print(f"Minimum rho found: {rho_minus:.10f}")
            print(f"w = {L['w']}")
        return rho_minus, L['w'], num_iterations

    # Bisection search
    while (rho_plus - rho_minus) > tol:
        rho_mid = (rho_plus + rho_minus) / 2
        M = solve_LP_given_rho(H_matrices_list, rho_mid, lp_solver, lp_params_constructor)
        num_iterations += 1
        
        if M['feasible']:
            rho_plus = rho_mid
            w_best = M['w']
            if verbose and num_iterations % 5 == 0:
                print(f"Iteration {num_iterations}: rho = {rho_mid:.10f} - FEASIBLE")
        else:
            rho_minus = rho_mid
            if verbose and num_iterations % 5 == 0:
                print(f"Iteration {num_iterations}: rho = {rho_mid:.10f} - INFEASIBLE")
    
    if verbose:
        print("-" * 60)
        print(f"Bisection converged after {num_iterations} iterations")
        print(f"Minimum rho found: {rho_plus:.10f}")
        print(f"Final interval width: {rho_plus - rho_minus:.2e}")
        print(f"w = {w_best}")

    return rho_plus, w_best, num_iterations


# For plotting purposes, we also code a line-search method; being able to control the step-size results in ``continuous" pictures of the evolution of w as rho gets contracted
def Rho_W_LineSearch(H_matrices_list: List[np.ndarray], rho_0: float = RHO_0, rho_step: float = 0.001, rho_min: float = 0.0, lp_solver: Callable = scipy_LP_solver, 
                                lp_params_constructor: Callable = scipy_LP_params_constructor, verbose: bool = True) -> Tuple[List[float], List[np.ndarray]]:
    """
    Iteratively find (ρ, w) pairs satisfying contractivity condition by decreasing ρ.
    
    Starting from rho_0 (close to 1), decreases rho by rho_step until either:
    1. LP becomes infeasible (no valid w exists), or
    2. rho reaches rho_min
    
    Since larger rho makes the LP easier to satisfy, we expect feasibility for large rho
    and infeasibility for small rho. This function finds the transition region.
    
    Uses the constraint: w ≥ 1 elementwise (no normalization).
    
    Parameters:
    -----------
    H_matrices_list : list of np.ndarray
        List of H(y) matrices for each feasible state y
    rho_0 : float, optional
        Initial (largest) rho value to test (default: 0.999999)
    rho_step : float, optional
        Amount to decrease rho each iteration (default: 0.001)
    rho_min : float, optional
        Minimum rho value to test; stop if rho < rho_min (default: 0.0)
    lp_solver : callable, optional
        LP solver function (default: scipy_LP_solver)
    lp_params_constructor : callable, optional
        LP parameter constructor function (default: scipy_LP_params_constructor)
    verbose : bool, optional
        If True, print progress information (default: True)
        
    Returns:
    --------
    tuple of (rho_list, w_list)
        - rho_list : list of float
            All rho values for which LP was feasible
        - w_list : list of np.ndarray
            Corresponding weight vectors w for each feasible rho
    """

    rho_list = []
    w_list = []
    
    # Validate input parameters
    if rho_min < 0:
        raise ValueError("rho_min must be non-negative")
    if rho_0 >= 1.0:
        raise ValueError(f"rho_0 must be strictly less than 1 (got rho_0 = {rho_0}). "
                        "The contractivity parameter rho must satisfy 0 <= rho < 1.")
    if rho_step <= 0:
        raise ValueError(f"rho_step must be positive (got rho_step = {rho_step})")
    
    # Initialize rho at starting value
    rho = rho_0
    
    if verbose:
        print(f"Finding contractivity pairs starting from rho = {rho_0}")
        print(f"Decreasing by {rho_step} until infeasible or rho < {rho_min}")
        print(f"Using solver: {lp_solver.__name__}")
        print("-" * 60)

    # Iterate: decrease rho until infeasible or below minimum
    iteration = 0
    while rho >= rho_min:
        iteration += 1
        
        # Solve LP for current rho
        result = solve_LP_given_rho(H_matrices_list, rho, lp_solver, lp_params_constructor)
        
        if result['feasible']:
            # Store feasible (rho, w) pair
            rho_list.append(rho)
            w_list.append(result['w'])
            
            if verbose and iteration % 10 == 0:
                print(f"Iteration {iteration}: rho = {rho:.6f} - FEASIBLE (w = {result['w']})")
        else:
            # LP became infeasible - stop iteration
            if verbose:
                print(f"Iteration {iteration}: rho = {rho:.6f} - INFEASIBLE")
                print(f"Stopping: LP is infeasible for rho = {rho:.6f}")
            break
        
        # Decrease rho for next iteration
        rho -= rho_step
    
    if verbose:
        if rho < rho_min:
            print(f"Stopping: reached minimum rho = {rho_min}")
        print("-" * 60)
        print(f"Found {len(rho_list)} feasible (rho, w) pairs")
        if len(rho_list) > 0:
            print(f"Rho range: [{min(rho_list):.6f}, {max(rho_list):.6f}]")
    
    return rho_list, w_list

